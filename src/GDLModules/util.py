    def f(row):
        u,v = row
        return np.array([np.cos(u) * (R + r*np.cos(v)), np.abs(np.sin(u) * (R + r*np.cos(v))), np.abs(r*np.sin(v))])

    data = np.apply_along_axis(f, 1, uv)
    return data
