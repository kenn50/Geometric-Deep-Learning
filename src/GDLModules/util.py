def plot3d(d, title="3D plot", color=None):
    """
    d: list of (dataset, label)

    color:
        None
        or list with one color specification per dataset.

        Examples:
            color=[alpha, "red"]
            color=["blue", "red"]
    """

    fig = go.Figure()
    

    if color is None:
        color = [None] * len(d)

    if len(color) != len(d):
        raise ValueError(
            f"Expected {len(d)} color specifications, got {len(color)}."
        )

    for d_tuple, c in zip(d, color):
        points = np.asarray(d_tuple[0]).reshape(-1, 3)

        marker = dict(size=2)


        if c is not None:
            if isinstance(c, str):
                # Fixed color for the whole dataset
                marker["color"] = c

            else:
                # Per-point color coding
                c = np.asarray(c).reshape(-1)

                if len(c) != len(points):
                    raise ValueError(
                        f"Color array for '{d_tuple[1]}' has {len(c)} values, "
                        f"but dataset has {len(points)} points."
                    )

                marker.update(
                    color=c,
                    colorscale="Viridis",
                    showscale=True,
                    colorbar=dict(title="Alpha"),
                )



        mode = "markers"
        if(len(d_tuple)>= 3):
            mode=d_tuple[2]
        

        fig.add_trace(
                go.Scatter3d(
                x=points[:, 0],
                y=points[:, 1],
                z=points[:, 2],
                mode=mode,
                name=d_tuple[1],
                marker=marker,
                line=dict(width=8),
            )
        )

    fig.update_layout(
        title=dict(
            text=title,
            font=dict(
                family="Arial",
                size=24,
                color="navy",
            ),
        ),
        margin=dict(t=60),
        scene=dict(
            xaxis_title="X",
            yaxis_title="Y",
            zaxis_title="Z",
            aspectmode="data",
        ),
    )

    return fig
    
    


class Sum(nn.Module):
    def __init__(self, *models):
        super().__init__()
        self.models = nn.ModuleList(models)

    def forward(self, x):
        return sum(model(x) for model in self.models)

class MLP(nn.Module):
    def __init__(self, input_dim, output_dim, hidden_structure, activation=nn.ReLU(), activation_last_layer=None, normalize=False): 
        super().__init__()
        def linear_layer(in_dim, out_dim):
            if normalize:
                return nn.utils.parametrizations.spectral_norm(nn.Linear(in_dim, out_dim))
            return nn.Linear(in_dim, out_dim)
        
        layers = []
        layers.append(linear_layer(input_dim, hidden_structure[0]))
        layers.append(activation)
        for i in range(len(hidden_structure) - 1):
            layers.append(linear_layer(hidden_structure[i], hidden_structure[i + 1]))
            layers.append(activation)
        layers.append(linear_layer(hidden_structure[-1], output_dim))
        if activation_last_layer is not None:
            layers.append(activation_last_layer)
        self.network = nn.Sequential(*layers)

    def forward(self, x):
        return self.network(x)
    
    

